/**
 * GenTx: the S2 APK's Marathi table, GENERATED from the prototype's own two string files
 * (design-marathi §2.2, §3; slice 1a, 27 Oct 2026).
 *
 * Inputs, all in `android/i18n/` (the ONE home of the tables, Amit's decision 3 of 27 Oct):
 * `strings-en.json` and `strings-mr.json` (byte copies of the prototype build's), and
 * `masters.tsv` (which keys show an identity value). Placeholder types come from the JSON's
 * own `placeholders` expressions, so there is no second shape file.
 *
 * Outputs: `Tx.kt` (one typed accessor per key, named by the key: every `.` and `-` becomes
 * `_`), `TxEn.kt` / `TxMr.kt` (the two string arrays, in chunks of at most [CHUNK] so no JVM
 * method nears 64 KB), `Masters.kt` (the display maps for identity values) in
 * `pano/src/main/.../pano/i18n/`, and `android/i18n/index.tsv`. All are committed, so a later
 * session can grep an accessor without building, and I18nTableTest fails when they are stale.
 *
 * It REFUSES (writes nothing) on anything it cannot type: keys out of step, a key with no
 * Marathi, a control character, an accessor collision, an unknown plural noun. A template whose
 * code picks an ENGLISH word for a placeholder (`left`/`right`, `Lock`/`Unlock`) gets no
 * accessor at all -- Marathi inflects that word -- and is listed in [Model.refused].
 *
 *   gen <i18nDir> <outDir>                 regenerate
 *   import <protoDir> <i18nDir> <outDir>   byte-copy the prototype's two tables, then regenerate
 *   check-proto <protoDir> <i18nDir>       fail if the prototype's tables differ from the committed ones
 */
object GenTx {

    const val PKG = "com.malletcrafts.interiorestimate.pano.i18n"
    const val HEADER = "// GENERATED by GenTx from android/i18n — do not edit. Regenerate: gradle :pano:i18nGen"
    val TABLES = listOf("strings-en.json", "strings-mr.json")
    const val MASTERS_TSV = "masters.tsv"
    const val INDEX_TSV = "index.tsv"

    /** Strings per generated filler method: 400 short literals stay far below the 64 KB method limit. */
    const val CHUNK = 400

    /** The one legitimately empty Marathi value: the English article `the ` (design §3.3, check 2). */
    const val EMPTY_OK = "sp.the"

    /** Tx's own members. Every accessor holds an `_`, so none can be one of these; the test pins it. */
    val MEMBERS = setOf("lang", "mr", "of", "EN", "MR", "tab")

    /** Kotlin's hard keywords: a placeholder named like one cannot be a parameter. */
    private val KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
        "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
        "val", "var", "when", "while",
    )

    /** Keys that never reach the phone: the prototype's feedback panel, its demo data, prototype-only screens. */
    fun skipReason(key: String, flags: List<String>): String? = when {
        key.startsWith("fb.") -> "fb (the prototype's feedback panel)"
        key.startsWith("demo.") -> "demo (demo data)"
        "prototype-only" in flags -> "prototype-only"
        else -> null
    }

    // ------------------------------------------------------------------ placeholder shapes

    /** What a placeholder's value can be, read from the JS expression that fills it in the prototype. */
    sealed class Shape {
        /** Anything: a name, a code, a figure already formatted. */
        object Word : Shape()
        /** A count: `x.length`, `x.size`, `nl`. */
        object Count : Shape()
        /** `n===1?'':'s'` (or reversed): an English plural suffix; Marathi drops it. */
        data class Suffix(val count: String, val whenOne: String, val otherwise: String) : Shape()
        /** `plural(n,'room')` / `pl(n,'surveyed room')`: a counted noun from the `noun.*` pairs. */
        data class Plural(val count: String, val noun: String) : Shape()
        /** `cond?'A':'B'` with both plain strings. */
        data class Alt(val a: String, val b: String) : Shape()
        /** `cond?' · '+x:''`: an optional tail with a known start. */
        data class Opt(val prefix: String) : Shape()
    }

    private val QS = """(?:'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")"""
    private val RX_SUFFIX = Regex("""\(?\s*([\w.$\[\]]+)\s*===?\s*1\s*\)?\s*\?\s*('e?s'|'')\s*:\s*('e?s'|'')""")
    private val RX_PLURAL = Regex("""(?:plural|pl)\(\s*(.+?)\s*,\s*'([\w ]+)'\s*\)""")
    private val RX_COUNT = Regex("""[\w.]+\.(?:length|size)|nl""")
    private val RX_ALT = Regex("""[^?]+?\?\s*($QS)\s*:\s*($QS)""")
    private val RX_OPT = Regex("""[^?]+?\?\s*(?:`([^`$]*)\$\{[\s\S]*`|'([^']*)'\s*\+[\s\S]*)\s*:\s*(?:''|"")""")

    private fun unquote(q: String): String {
        val b = q.substring(1, q.length - 1)
        val sb = StringBuilder()
        var i = 0
        while (i < b.length) {
            if (b[i] == '\\' && i + 1 < b.length) { sb.append(b[i + 1]); i += 2 } else { sb.append(b[i]); i++ }
        }
        return sb.toString()
    }

    /** The prototype build's `ph_kind` (integrate57.py), with the suffix and plural read whole. */
    fun shapeOf(expr: String): Shape {
        val x = expr.trim()
        RX_SUFFIX.matchEntire(x)?.let { m ->
            val one = unquote(m.groupValues[2]); val other = unquote(m.groupValues[3])
            if ((one.isEmpty()) != (other.isEmpty())) return Shape.Suffix(m.groupValues[1], one, other)
        }
        RX_PLURAL.matchEntire(x)?.let { m -> return Shape.Plural(m.groupValues[1], m.groupValues[2].replace(' ', '_')) }
        if (RX_COUNT.matches(x)) return Shape.Count
        RX_ALT.matchEntire(x)?.let { m -> return Shape.Alt(unquote(m.groupValues[1]), unquote(m.groupValues[2])) }
        RX_OPT.matchEntire(x)?.let { m ->
            val pre = if (m.groups[1] != null) m.groupValues[1] else m.groupValues[2]
            if (pre.isNotBlank()) return Shape.Opt(pre)
        }
        return Shape.Word
    }

    private val PH = Regex("""\{(\w+)\}""")
    fun placeholders(s: String): List<String> = PH.findAll(s).map { it.groupValues[1] }.distinct().toList()

    /** An alternative made only of glyphs or codes passes as written; one with an English word is refused. */
    private fun latinWord(s: String) = Regex("[A-Za-z]").containsMatchIn(s)

    // ------------------------------------------------------------------ the model

    enum class Kind { STATIC, TEMPLATE, NOUN, NOUN_OTHER, REFUSED, SKIPPED }

    /** One generated parameter: Kotlin name, type, and what the caller passes. */
    data class Param(val name: String, val type: String, val doc: String)

    class Entry(
        val key: String, val en: String, val mr: String, val flags: List<String>, val kind: Kind,
        /** The accessor; null for a refused or skipped key. */
        val accessor: String?,
        val params: List<Param> = emptyList(),
        /** placeholder -> the Kotlin expression that fills it. */
        val fills: List<Pair<String, String>> = emptyList(),
        val slot: Int = -1, val slotOther: Int = -1,
        val why: String = "",
    )

    class Model(
        val entries: List<Entry>,
        val enTab: List<String>, val mrTab: List<String>,
        /** map name -> (English value, accessor) in declaration order. */
        val masters: Map<String, List<Pair<String, String>>>,
        val errors: List<String>,
    ) {
        val refused: List<String> get() = entries.filter { it.kind == Kind.REFUSED }.map { it.key }
        val byKey: Map<String, Entry> get() = entries.associateBy { it.key }
        /** Every accessor name Tx declares, the `pl_` plurals included. */
        val accessors: List<String> get() = entries.flatMap { e ->
            when (e.kind) {
                Kind.NOUN -> listOf(e.accessor!!, plName(e.key))
                Kind.STATIC, Kind.TEMPLATE -> listOf(e.accessor!!)
                else -> emptyList()
            }
        }
    }

    /** `app.display` -> `app_display`: every `.` and `-` becomes `_` (design §2.2). */
    fun accessorOf(key: String): String = key.replace('.', '_').replace('-', '_')

    /** `noun.room` -> `pl_room`: "3 rooms" / "3 खोल्या". */
    fun plName(nounKey: String): String = "pl_" + accessorOf(nounKey.removePrefix("noun."))

    /** The control characters a table may carry: a newline (a two-line message) and the zero-width joiner (अ‍ॅप). */
    fun badChar(c: Char): Boolean {
        val o = c.code
        if (c == '\n' || o == 0x200D) return false
        return o < 0x20 || o in 0x7F..0x9F || o in 0x200B..0x200F || o in 0x202A..0x202E ||
            o in 0x2066..0x2069 || o == 0x2028 || o == 0x2029 || o == 0xFEFF
    }

    @Suppress("UNCHECKED_CAST")
    fun parseTable(text: String, field: String): LinkedHashMap<String, Map<String, Any?>> {
        val root = MiniJson.parse(text) as? Map<String, Any?> ?: error("not a JSON object")
        val out = LinkedHashMap<String, Map<String, Any?>>()
        for ((k, v) in root) {
            val o = v as? Map<String, Any?> ?: error("$k: not an object")
            require(o[field] is String) { "$k: no \"$field\" string" }
            out[k] = o
        }
        return out
    }

    @Suppress("UNCHECKED_CAST")
    private fun strList(v: Any?): List<String> = (v as? List<Any?>)?.map { it.toString() } ?: emptyList()

    /** Builds the whole model; [Model.errors] non-empty means nothing may be written. */
    @Suppress("UNCHECKED_CAST")
    fun model(enText: String, mrText: String, mastersText: String): Model {
        val errors = ArrayList<String>()
        val en = parseTable(enText, "en")
        val mr = parseTable(mrText, "mr")
        val enKeys = en.keys.toList(); val mrKeys = mr.keys.toList()
        if (enKeys != mrKeys) {
            val onlyEn = enKeys - mrKeys.toSet(); val onlyMr = mrKeys - enKeys.toSet()
            errors += "strings-en.json and strings-mr.json are not mirrors: only in en ${onlyEn.take(25)}, only in mr ${onlyMr.take(25)}" +
                (if (onlyEn.isEmpty() && onlyMr.isEmpty()) ", same keys in a different order" else "")
            return Model(emptyList(), emptyList(), emptyList(), emptyMap(), errors)
        }
        val enTab = ArrayList<String>(); val mrTab = ArrayList<String>()
        fun slot(e: String, m: String): Int { enTab += e; mrTab += m; return enTab.size - 1 }

        val nouns = enKeys.filter { it.startsWith("noun.") && !it.endsWith(".other") }.associateBy { it.removePrefix("noun.") }
        val entries = ArrayList<Entry>()
        val names = HashMap<String, String>()          // accessor -> key
        fun claim(name: String, key: String): Boolean {
            val was = names.putIfAbsent(name, key)
            if (was != null) { errors += "$key: accessor $name already belongs to $was"; return false }
            if (name in MEMBERS || !name.contains('_')) { errors += "$key: accessor $name collides with a Tx member"; return false }
            return true
        }

        for (k in enKeys) {
            val e = en.getValue(k); val m = mr.getValue(k)
            val enV = e["en"] as String; val mrV = m["mr"] as String
            val flags = strList(e["flags"])
            for ((which, s) in listOf("en" to enV, "mr" to mrV)) {
                s.firstOrNull { badChar(it) }?.let { errors += "$k: control character U+%04X in $which".format(java.util.Locale.ROOT, it.code) }
            }
            if (!Regex("""[A-Za-z][A-Za-z0-9_.\-]*""").matches(k)) errors += "$k: not a key the accessor rule can name"
            val skip = skipReason(k, flags)
            if (skip != null) { entries += Entry(k, enV, mrV, flags, Kind.SKIPPED, null, why = skip); continue }
            if (k.startsWith("noun.") && k.endsWith(".other")) {
                entries += Entry(k, enV, mrV, flags, Kind.NOUN_OTHER, accessorOf(k.removeSuffix(".other")), why = "the plural form of ${k.removeSuffix(".other")}")
                continue
            }
            if (mrV.isEmpty() && k != EMPTY_OK) errors += "$k: no Marathi"
            val acc = accessorOf(k)
            if (k.startsWith("noun.")) {
                val other = "$k.other"
                if (other !in en) { errors += "$k: no $other"; continue }
                if (!claim(acc, k) || !claim(plName(k), k)) continue
                val i = slot(enV, mrV)
                val j = slot(en.getValue(other)["en"] as String, mr.getValue(other)["mr"] as String)
                entries += Entry(k, enV, mrV, flags, Kind.NOUN, acc, listOf(Param("n", "Int", "the count")), slot = i, slotOther = j)
                continue
            }
            if (e["kind"] != "template") {
                if (PH.containsMatchIn(enV)) errors += "$k: a static with a {placeholder}"
                if (!claim(acc, k)) continue
                entries += Entry(k, enV, mrV, flags, Kind.STATIC, acc, slot = slot(enV, mrV))
                continue
            }
            // ---- a template
            val exprs = ((e["placeholders"] as? Map<String, Any?>) ?: emptyMap()).mapValues { it.value.toString().trim() }
            val used = placeholders(enV)
            if (used.toSet() != exprs.keys) { errors += "$k: placeholders ${exprs.keys} but the English uses $used"; continue }
            val mrUsed = placeholders(mrV)
            val shapes = exprs.mapValues { shapeOf(it.value) }
            val extra = mrUsed - used.toSet()
            if (extra.isNotEmpty()) { errors += "$k: Marathi placeholders $extra are not in the English"; continue }
            val dropped = used - mrUsed.toSet()
            dropped.filter { shapes[it] !is Shape.Suffix }.takeIf { it.isNotEmpty() }?.let {
                errors += "$k: the Marathi drops $it, and only a plural suffix may be dropped"
            }
            val refusedBy = shapes.entries.firstOrNull { (_, s) -> s is Shape.Alt && "diagnostic-log" !in flags && (latinWord(s.a) || latinWord(s.b)) }
            if (refusedBy != null) {
                val s = refusedBy.value as Shape.Alt
                entries += Entry(k, enV, mrV, flags, Kind.REFUSED, null,
                    why = "{${refusedBy.key}} is the English '${s.a}' / '${s.b}', chosen in code; split into two whole keys in the prototype table")
                continue
            }
            // A suffix or a word-only plural whose count is ANOTHER placeholder's expression folds into it.
            val norm = exprs.mapValues { it.value.replace(Regex("\\s+"), "") }
            fun siblingOf(p: String, count: String): String? =
                used.firstOrNull { it != p && norm[it] == count.replace(Regex("\\s+"), "") && (shapes[it] == Shape.Word || shapes[it] == Shape.Count) }
            val foldInto = HashMap<String, String>()
            for (p in used) {
                when (val s = shapes.getValue(p)) {
                    is Shape.Suffix -> siblingOf(p, s.count)?.let { foldInto[p] = it }
                    is Shape.Plural -> siblingOf(p, s.count)?.let { foldInto[p] = it }
                    else -> {}
                }
            }
            val asInt = foldInto.values.toSet()
            val params = ArrayList<Param>(); val fills = ArrayList<Pair<String, String>>()
            var bad = false
            fun pname(p: String) = if (p in KEYWORDS) { errors += "$k: placeholder {$p} is a Kotlin keyword"; bad = true; p } else p
            for (p in used) {
                val s = shapes.getValue(p)
                val sib = foldInto[p]
                when {
                    s is Shape.Suffix && sib != null -> fills += p to suffixCall(s, sib)
                    s is Shape.Suffix -> { val n = pname(p) + "N"; params += Param(n, "Int", "the count {$p} agrees with"); fills += p to suffixCall(s, n) }
                    s is Shape.Plural -> {
                        val noun = nouns[s.noun]
                        if (noun == null) { errors += "$k: {$p} is a plural of '${s.noun}', and there is no noun.${s.noun}"; bad = true }
                        else if (sib != null) fills += p to "${accessorOf(noun)}($sib)"
                        else { val n = pname(p) + "N"; params += Param(n, "Int", "the count, shown as \"3 ${s.noun.replace('_', ' ')}s\""); fills += p to "${plName(noun)}($n)" }
                    }
                    p in asInt || s == Shape.Count -> { params += Param(pname(p), "Int", "a count"); fills += p to "${p}.toString()" }
                    s is Shape.Opt && s.prefix.isNotBlank() && !latinWord(s.prefix) ->
                        { params += Param(pname(p), "String?", "null, or the tail; \"${s.prefix}\" is put before it"); fills += p to "opt(${kt(s.prefix)}, $p)" }
                    s is Shape.Opt -> { params += Param(pname(p), "String?", "null, or the WHOLE tail from its own key"); fills += p to "$p ?: \"\"" }
                    s is Shape.Alt -> { params += Param(pname(p), "String", "'${s.a}' or '${s.b}', as written"); fills += p to p }
                    else -> { params += Param(pname(p), "String", "as given"); fills += p to p }
                }
            }
            val pn = params.map { it.name }
            pn.groupBy { it }.filter { it.value.size > 1 }.keys.takeIf { it.isNotEmpty() }?.let { errors += "$k: parameter names repeat: $it"; bad = true }
            if (bad || !claim(acc, k)) continue
            entries += Entry(k, enV, mrV, flags, Kind.TEMPLATE, acc, params, fills, slot = slot(enV, mrV))
        }
        val masters = masters(mastersText, entries, errors)
        return Model(entries, enTab, mrTab, masters, errors)
    }

    private fun suffixCall(s: Shape.Suffix, n: String) = "suf($n, ${kt(s.whenOne)}, ${kt(s.otherwise)})"

    // ------------------------------------------------------------------ Masters

    /** Families whose every key is an identity value: the ERP and S5 masters (flags erp-master / s5-master). */
    fun masterFamilies(entries: List<Entry>): List<String> =
        entries.filter { "erp-master" in it.flags || "s5-master" in it.flags }.map { it.key.substringBefore('.') }.distinct()

    /**
     * One map per master family, plus the maps `masters.tsv` declares for identity values whose
     * keys live in other families (a quote stage, a work state, a service, a mark type...).
     * Each maps the key's ENGLISH, byte for byte, to its accessor; two keys with one English in
     * one map is refused, so a homonym can never have a second answer.
     */
    fun masters(text: String, entries: List<Entry>, errors: MutableList<String>): Map<String, List<Pair<String, String>>> {
        val byKey = entries.associateBy { it.key }
        val out = LinkedHashMap<String, MutableList<Entry>>()
        for (fam in masterFamilies(entries)) {
            out.getOrPut(fam) { ArrayList() } += entries.filter { it.key.startsWith("$fam.") && ("erp-master" in it.flags || "s5-master" in it.flags) }
        }
        for ((n, raw) in text.lines().withIndex()) {
            val line = raw.substringBefore('#').trim()
            if (line.isEmpty()) continue
            val cols = line.split('\t').map { it.trim() }.filter { it.isNotEmpty() }
            if (cols.size != 2) { errors += "masters.tsv:${n + 1}: want 'map<TAB>key', got '$raw'"; continue }
            val (map, key) = cols
            if (!Regex("[a-z][a-z_]*").matches(map)) { errors += "masters.tsv:${n + 1}: map '$map' is not a lower-case name"; continue }
            val e = byKey[key]
            if (e == null || (e.kind != Kind.STATIC)) { errors += "masters.tsv:${n + 1}: $key is not a static key of the table"; continue }
            out.getOrPut(map) { ArrayList() } += e
        }
        val result = LinkedHashMap<String, List<Pair<String, String>>>()
        for ((map, list) in out) {
            val seen = HashMap<String, String>()
            val pairs = ArrayList<Pair<String, String>>()
            for (e in list) {
                if (e.kind != Kind.STATIC) { errors += "Masters.$map: ${e.key} is not a static"; continue }
                val was = seen.putIfAbsent(e.en, e.key)
                if (was != null) { if (was != e.key) errors += "Masters.$map: '${e.en}' is both $was and ${e.key}"; continue }
                pairs += e.en to e.accessor!!
            }
            result[map] = pairs
        }
        return result
    }

    // ------------------------------------------------------------------ writing

    /** A Kotlin string literal for [s]: escapes, `$`, and a newline; the zero-width joiner stays as it is. */
    fun kt(s: String): String {
        val sb = StringBuilder("\"")
        for (c in s) when (c) {
            '\\' -> sb.append("\\\\"); '"' -> sb.append("\\\""); '$' -> sb.append("\\$"); '\n' -> sb.append("\\n")
            else -> sb.append(c)
        }
        return sb.append('"').toString()
    }

    private fun doc(s: String) = s.replace("*/", "* /").replace("/*", "/ *").replace("\n", " ⏎ ")
    private fun short(s: String, n: Int = 100) = if (s.length <= n) s else s.take(n - 1) + "…"

    fun txKt(m: Model): String {
        val sb = StringBuilder()
        sb.append(HEADER).append('\n')
        sb.append("// From strings-en.json / strings-mr.json: ${m.entries.size} keys, ${m.accessors.size} accessors, ")
        sb.append("${m.refused.size} refused, ${m.entries.count { it.kind == Kind.SKIPPED }} skipped. Key <-> accessor: android/i18n/index.tsv.\n")
        sb.append("@file:Suppress(\"FunctionName\", \"PropertyName\", \"LocalVariableName\", \"unused\")\n\n")
        sb.append("package $PKG\n\n")
        sb.append("/** The two languages. The phone's choice is the भाषा · Language row alone, never the system language. */\n")
        sb.append("enum class Lang { EN, MR }\n\n")
        sb.append("/**\n * The phone's texts in one language: one accessor per prototype key, named by the key\n")
        sb.append(" * (`app.display` is `app_display`). [EN] and [MR] are the only two; [of] reads the stored choice.\n */\n")
        sb.append("class Tx private constructor(val lang: Lang, private val tab: Array<String>) {\n\n")
        sb.append("    /** Marathi is on: only for layout (the four line heights the prototype measured), never to pick a text. */\n")
        sb.append("    val mr: Boolean get() = lang == Lang.MR\n\n")
        sb.append("    companion object {\n")
        sb.append("        val EN: Tx by lazy { Tx(Lang.EN, TxEn.table()) }\n")
        sb.append("        val MR: Tx by lazy { Tx(Lang.MR, TxMr.table()) }\n\n")
        sb.append("        /** The stored choice: exactly \"mr\" is Marathi; unset, any other value or an unreadable one is English (the prototype's rule). */\n")
        sb.append("        fun of(code: String?): Tx = if (code == \"mr\") MR else EN\n")
        sb.append("    }\n\n")
        sb.append("    /** Fills every {name} of [t] in ONE pass: a value that itself holds {x} (a typed note) is never filled again. */\n")
        sb.append("    private fun f(t: String, vararg kv: String): String {\n")
        sb.append("        val sb = StringBuilder(t.length + 16)\n")
        sb.append("        var i = 0\n")
        sb.append("        while (i < t.length) {\n")
        sb.append("            val c = t[i]\n")
        sb.append("            if (c == '{') {\n")
        sb.append("                val j = t.indexOf('}', i + 1)\n")
        sb.append("                if (j > i) {\n")
        sb.append("                    val name = t.substring(i + 1, j)\n")
        sb.append("                    var k = 0\n")
        sb.append("                    while (k < kv.size && kv[k] != name) k += 2\n")
        sb.append("                    if (k < kv.size) { sb.append(kv[k + 1]); i = j + 1; continue }\n")
        sb.append("                }\n")
        sb.append("            }\n")
        sb.append("            sb.append(c)\n")
        sb.append("            i++\n")
        sb.append("        }\n")
        sb.append("        return sb.toString()\n")
        sb.append("    }\n\n")
        sb.append("    /** An English plural suffix; Marathi forms the plural in the noun, so it is always empty there. */\n")
        sb.append("    private fun suf(n: Int, one: String, other: String): String = if (mr) \"\" else if (n == 1) one else other\n\n")
        sb.append("    /** An optional tail: nothing, or its separator and the value. */\n")
        sb.append("    private fun opt(sep: String, v: String?): String = if (v == null) \"\" else sep + v\n")
        for (e in m.entries) {
            when (e.kind) {
                Kind.STATIC -> {
                    sb.append("\n    /** `${e.key}` — ${doc(short(e.en))} */\n")
                    sb.append("    val ${e.accessor}: String get() = tab[${e.slot}]\n")
                }
                Kind.NOUN -> {
                    sb.append("\n    /** `${e.key}` / `${e.key}.other` — ${doc(e.en)} / ${doc(m.enTab[e.slotOther])} */\n")
                    sb.append("    fun ${e.accessor}(n: Int): String = if (n == 1) tab[${e.slot}] else tab[${e.slotOther}]\n")
                    sb.append("    /** \"3 ${doc(m.enTab[e.slotOther])}\": the count, a space, and [${e.accessor}]. */\n")
                    sb.append("    fun ${plName(e.key)}(n: Int): String = n.toString() + \" \" + ${e.accessor}(n)\n")
                }
                Kind.TEMPLATE -> {
                    sb.append("\n    /** `${e.key}` — ${doc(short(e.en))}")
                    for (p in e.params) sb.append("\n     * @param ${p.name} ${doc(p.doc)}")
                    sb.append(" */\n")
                    val ps = e.params.joinToString(", ") { "${it.name}: ${it.type}" }
                    val fs = e.fills.joinToString(", ") { (ph, ex) -> "${kt(ph)}, $ex" }
                    sb.append("    fun ${e.accessor}($ps): String = f(tab[${e.slot}], $fs)\n")
                }
                else -> {}
            }
        }
        sb.append("}\n")
        return sb.toString()
    }

    fun tableKt(obj: String, lang: String, vals: List<String>): String {
        val sb = StringBuilder()
        sb.append(HEADER).append('\n')
        sb.append("@file:Suppress(\"SpellCheckingInspection\")\n\n")
        sb.append("package $PKG\n\n")
        sb.append("/** The $lang strings of [Tx], by slot. Filled in methods of at most $CHUNK, so none nears the JVM's 64 KB. */\n")
        sb.append("internal object $obj {\n")
        sb.append("    fun table(): Array<String> {\n")
        sb.append("        val a = arrayOfNulls<String>(${vals.size})\n")
        val chunks = (vals.indices step CHUNK).toList()
        for ((ci, _) in chunks.withIndex()) sb.append("        p$ci(a)\n")
        sb.append("        return a.requireNoNulls()\n")
        sb.append("    }\n")
        for ((ci, start) in chunks.withIndex()) {
            sb.append("\n    private fun p$ci(a: Array<String?>) {\n")
            for (i in start until minOf(start + CHUNK, vals.size)) sb.append("        a[$i] = ${kt(vals[i])}\n")
            sb.append("    }\n")
        }
        sb.append("}\n")
        return sb.toString()
    }

    fun mastersKt(m: Model): String {
        val sb = StringBuilder()
        sb.append(HEADER).append('\n')
        sb.append("// Maps: the erp-master / s5-master families of the table, and the maps declared in android/i18n/masters.tsv.\n\n")
        sb.append("package $PKG\n\n")
        sb.append("/**\n * Identity values SHOWN through the table. Storage, the wire and every comparison keep the\n")
        sb.append(" * English value byte for byte; only the text on screen changes (design §2.6). A typed name, or a\n")
        sb.append(" * master the map does not hold, is shown as typed: data with no translation, not a fallback.\n */\n")
        sb.append("object Masters {\n")
        for ((map, pairs) in m.masters) {
            sb.append("\n    /** ${pairs.size} values. */\n")
            sb.append("    fun $map(tx: Tx, value: String): String = when (value) {\n")
            for ((en, acc) in pairs) sb.append("        ${kt(en)} -> tx.$acc\n")
            sb.append("        else -> value\n")
            sb.append("    }\n")
        }
        sb.append("\n    /** The map names, in order: for the tests that walk every identity list. */\n")
        sb.append("    val MAPS: List<String> = listOf(${m.masters.keys.joinToString(", ") { kt(it) }})\n")
        sb.append("}\n")
        return sb.toString()
    }

    fun indexTsv(m: Model): String {
        val sb = StringBuilder()
        sb.append("# GENERATED by GenTx from android/i18n — do not edit. Regenerate: gradle :pano:i18nGen\n")
        sb.append("# One row per prototype key: key, accessor on Tx (- when none), kind, parameters or why there is none.\n")
        sb.append("key\taccessor\tkind\tparameters\n")
        for (e in m.entries) {
            val kind = e.kind.name.lowercase().replace('_', '-')
            val acc = when (e.kind) {
                Kind.NOUN -> "${e.accessor} ${plName(e.key)}"
                Kind.NOUN_OTHER -> e.accessor!!
                else -> e.accessor ?: "-"
            }
            val ps = when (e.kind) {
                Kind.TEMPLATE -> e.params.joinToString(" · ") { "${it.name}: ${it.type}" }.ifEmpty { "-" }
                Kind.NOUN -> "n: Int"
                Kind.REFUSED, Kind.SKIPPED, Kind.NOUN_OTHER -> e.why
                else -> "-"
            }
            sb.append(e.key).append('\t').append(acc).append('\t').append(kind).append('\t').append(ps.replace('\t', ' ')).append('\n')
        }
        return sb.toString()
    }

    /** Every generated file, by its path relative to `android/`. */
    fun files(m: Model): Map<String, String> = linkedMapOf(
        "pano/src/main/kotlin/com/malletcrafts/interiorestimate/pano/i18n/Tx.kt" to txKt(m),
        "pano/src/main/kotlin/com/malletcrafts/interiorestimate/pano/i18n/TxEn.kt" to tableKt("TxEn", "English", m.enTab),
        "pano/src/main/kotlin/com/malletcrafts/interiorestimate/pano/i18n/TxMr.kt" to tableKt("TxMr", "Marathi", m.mrTab),
        "pano/src/main/kotlin/com/malletcrafts/interiorestimate/pano/i18n/Masters.kt" to mastersKt(m),
        "i18n/$INDEX_TSV" to indexTsv(m),
    )

    /** Reads the three inputs from [i18nDir] and builds the model. */
    fun modelOf(i18nDir: File): Model = model(
        i18nDir.resolve(TABLES[0]).readText(),
        i18nDir.resolve(TABLES[1]).readText(),
        i18nDir.resolve(MASTERS_TSV).readText(),
    )

    private fun generate(i18nDir: File, outDir: File): Int {
        val m = modelOf(i18nDir)
        if (m.errors.isNotEmpty()) {
            System.err.println("GenTx refused, nothing written (${m.errors.size}):")
            m.errors.forEach { System.err.println("  $it") }
            return 1
        }
        val android = i18nDir.absoluteFile.parentFile
        for ((rel, text) in files(m)) {
            val f = if (rel.startsWith("i18n/")) android.resolve(rel) else outDir.resolve(rel.substringAfterLast('/'))
            f.parentFile.mkdirs()
            if (!f.isFile || f.readText() != text) { f.writeText(text); println("wrote $f") }
        }
        println("GenTx: ${m.accessors.size} accessors, ${m.refused.size} refused (${m.refused.joinToString(", ")}), ${m.masters.size} master maps")
        return 0
    }

    private fun sameBytes(a: File, b: File) = a.isFile && b.isFile && a.readBytes().contentEquals(b.readBytes())

    @JvmStatic
    fun main(args: Array<String>) {
        val code = when (args.firstOrNull()) {
            "gen" -> generate(File(args[1]), File(args[2]))
            "import" -> {
                val proto = File(args[1]); val i18n = File(args[2])
                val missing = TABLES.filter { !proto.resolve(it).isFile }
                if (missing.isNotEmpty()) { System.err.println("no $missing in $proto"); 1 } else {
                    for (t in TABLES) Files.copy(proto.resolve(t).toPath(), i18n.resolve(t).toPath(), StandardCopyOption.REPLACE_EXISTING)
                    println("imported ${TABLES.joinToString()} from $proto (byte copies)")
                    generate(i18n, File(args[3]))
                }
            }
            "check-proto" -> {
                val proto = File(args[1]); val i18n = File(args[2])
                val differ = TABLES.filter { !sameBytes(proto.resolve(it), i18n.resolve(it)) }
                if (differ.isEmpty()) { println("the prototype's tables equal android/i18n byte for byte"); 0 } else {
                    System.err.println("the prototype build $proto and android/i18n differ in $differ: import the prototype's (gradle :pano:i18nImport -Pproto=$proto) or rebuild the prototype from android/i18n")
                    1
                }
            }
            else -> { System.err.println("usage: gen <i18nDir> <outDir> | import <protoDir> <i18nDir> <outDir> | check-proto <protoDir> <i18nDir>"); 2 }
        }
        if (code != 0) exitProcess(code)
    }
